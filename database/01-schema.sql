CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0),
    type INTEGER NOT NULL REFERENCES transaction_types (id),
    category_id INTEGER NOT NULL DEFAULT 12 REFERENCES categories (id),
    description TEXT,
    payment_method TEXT,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    source_text TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS transactions_type_occurred_at_idx
    ON transactions (type, occurred_at DESC);
CREATE INDEX IF NOT EXISTS transactions_occurred_at_idx
    ON transactions (occurred_at DESC);

CREATE TABLE IF NOT EXISTS events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    start_time TIMESTAMPTZ NOT NULL,
    end_time TIMESTAMPTZ,
    location TEXT,
    notes TEXT,
    source_text TEXT NOT NULL,
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT events_valid_period CHECK (end_time IS NULL OR end_time > start_time)
);

CREATE INDEX IF NOT EXISTS events_start_time_idx
    ON events (start_time);
CREATE INDEX IF NOT EXISTS events_period_idx
    ON events (start_time, end_time);
CREATE INDEX IF NOT EXISTS events_recorded_at_idx
    ON events (recorded_at DESC);
